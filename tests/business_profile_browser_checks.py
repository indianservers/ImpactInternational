"""Business profile UI checks against an explicitly isolated QA database/API."""
import json, os, pathlib
from playwright.sync_api import sync_playwright, expect
from support import Client, BASE
assert BASE == 'http://127.0.0.1:5098'
assert os.environ.get('CLUBS_TEST_DATABASE') == 'clubs_business_profile_qa_20261117'
UI='http://127.0.0.1:1250'
out=pathlib.Path('docs/qa/business-profile');out.mkdir(parents=True,exist_ok=True)
checks=[]
def check(name,ok):
 checks.append({'test':name,'passed':bool(ok)});assert ok,name
c=Client();assert c.login('member.club1@example.test')[0]==200
v=Client();assert v.login('member.club2@example.test')[0]==200
with sync_playwright() as p:
 b=p.chromium.launch()
 ctx=b.new_context(viewport={'width':1440,'height':1000})
 ctx.add_cookies([{'name':x.name,'value':x.value,'domain':'127.0.0.1','path':x.path} for x in c.jar])
 page=ctx.new_page();errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(UI+'/app/networking/profile');expect(page.get_by_label('Business category',exact=True)).to_be_visible()
 page.get_by_label('Business category',exact=True).fill('Professional services')
 check('Changing category clears subcategory',page.get_by_label('Business subcategory',exact=True).input_value()=='')
 page.get_by_label('Business category',exact=True).fill('Technology')
 page.get_by_label('Business subcategory',exact=True).fill('Software development')
 page.get_by_label('About your business',exact=False).fill('We build thoughtful web applications and automation for growing businesses.')
 page.get_by_label('Business tags',exact=True).fill('UX design')
 page.get_by_label('Business tags',exact=True).press('Enter')
 check('Enter creates business tag',page.get_by_role('button',name='Remove tag UX design',exact=True).count()==1)
 page.get_by_label('Business tags',exact=True).fill('ux DESIGN')
 page.get_by_label('Business tags',exact=True).press('Enter')
 check('Tags deduplicate without case sensitivity',page.get_by_role('button',name='Remove tag UX design',exact=True).count()==1)
 page.get_by_label('Business tags',exact=True).fill('Temporary')
 page.get_by_label('Business tags',exact=True).press('Enter')
 page.get_by_role('button',name='Remove tag Temporary',exact=True).click()
 check('Business tag removal works',page.get_by_role('button',name='Remove tag Temporary',exact=True).count()==0)
 page.get_by_role('button',name='Save networking profile',exact=True).click()
 expect(page.get_by_text('Networking profile saved.',exact=True)).to_be_visible()
 page.reload();expect(page.get_by_label('Business category',exact=True)).to_have_value('Technology')
 check('Saved business specialty survives reload',page.get_by_label('Business subcategory',exact=True).input_value()=='Software development')
 check('Saved business tags survive reload',page.get_by_role('button',name='Remove tag UX design',exact=True).count()==1)
 page.screenshot(path=str(out/'editor-desktop.png'),full_page=True)
 status,own=c.req('/membership/me');assert status==200
 membership=next(m for m in own['memberships'] if m['status']=='Active')
 page.goto(UI+'/app/members/'+membership['id']+'?tab=Business+profile')
 expect(page.get_by_role('button',name='Edit business profile',exact=True)).to_be_visible()
 check('Member business profile tab renders saved company',page.locator('.business-profile-card').get_by_text('Aurora Digital Studio',exact=True).count()==1)
 page.screenshot(path=str(out/'member-business-tab.png'),full_page=True)
 page.get_by_role('button',name='Edit business profile',exact=True).click()
 expect(page.get_by_label('Business subcategory',exact=True)).to_be_visible()
 check('Edit business shortcut opens professional fields',page.get_by_label('Business subcategory',exact=True).input_value()=='Software development')
 page.get_by_role('button',name='Cancel',exact=True).click()
 page.goto(UI+'/app/networking/profile')
 expect(page.get_by_label('Business subcategory',exact=True)).to_be_visible()
 page.set_viewport_size({'width':390,'height':844});check('Editor mobile has no horizontal overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
 page.screenshot(path=str(out/'editor-mobile.png'),full_page=True)
 viewer=b.new_context(viewport={'width':1440,'height':1000});viewer.add_cookies([{'name':x.name,'value':x.value,'domain':'127.0.0.1','path':x.path} for x in v.jar])
 vp=viewer.new_page();vp.on('pageerror',lambda e:errors.append(str(e)));vp.goto(UI+'/app/networking')
 expect(vp.get_by_label('Business category',exact=True)).to_be_visible()
 vp.get_by_label('Business category',exact=True).select_option('Technology')
 vp.get_by_label('Subcategory',exact=True).select_option('Software development')
 vp.get_by_label('Business tag',exact=True).select_option('Automation')
 expect(vp.get_by_role('heading',name='Demo Member 0001-01',exact=True)).to_be_visible()
 check('Category/subcategory/tag filters discover saved business',vp.locator('.nw-person').count()==1)
 vp.screenshot(path=str(out/'discovery-desktop.png'),full_page=True)
 vp.get_by_role('button',name='View profile & connect',exact=False).click()
 expect(vp.get_by_role('region',name='Business profile',exact=True)).to_be_visible()
 check('Business card includes company and tags',vp.locator('.business-profile-card').get_by_text('Aurora Digital Studio',exact=True).count()==1 and vp.locator('.business-profile-card').get_by_text('Automation',exact=True).count()==1)
 check('Business title stays white on teal background',vp.locator('.business-profile-card header h2').evaluate("el=>getComputedStyle(el).color")=='rgb(255, 255, 255)')
 vp.screenshot(path=str(out/'business-card-desktop.png'),full_page=True)
 vp.set_viewport_size({'width':390,'height':844});check('Business modal mobile has no horizontal overflow',vp.evaluate('document.documentElement.scrollWidth<=innerWidth'))
 vp.screenshot(path=str(out/'business-card-mobile.png'),full_page=True)
 vp.evaluate("document.documentElement.dataset.theme='dark'")
 vp.screenshot(path=str(out/'business-card-dark.png'),full_page=True)
 vp.get_by_role('button',name='Close networking profile',exact=True).click()
 vp.get_by_role('button',name='Clear filters',exact=True).click()
 check('Clear filters resets business filters',all(vp.get_by_label(label,exact=True).input_value()=='' for label in ['Business category','Subcategory','Business tag']))
 check('No browser runtime errors',not errors)
 b.close()
(out/'browser-checks.json').write_text(json.dumps(checks,indent=2))
print(f'Passed {len(checks)} browser checks')
